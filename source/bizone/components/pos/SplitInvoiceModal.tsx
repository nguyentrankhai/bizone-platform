"use client";

import { useEffect, useMemo, useState } from "react";
import { Combine, Minus, PauseCircle, Play, Plus, Scissors, Trash2 } from "lucide-react";
import { Modal } from "@/components/ui/Modal";
import { cn } from "@/lib/utils";
import type { CartSnapshot, HeldCartSummary } from "@/lib/pos/protocol";
import { fmtDate, fmtMoney } from "@/components/inventory/shared";

type Tab = "split" | "held";

interface Props {
  open: boolean;
  initialTab?: Tab;
  cart: CartSnapshot | null;
  held: HeldCartSummary[];
  online: boolean;
  onClose: () => void;
  onSplit: (items: { itemId: string; quantity: number }[], label?: string) => Promise<void>;
  onHold: (label?: string) => Promise<void>;
  onResume: (heldId: string) => Promise<void>;
  onMerge: (heldIds: string[]) => Promise<void>;
  onDiscard: (heldId: string) => Promise<void>;
}

/**
 * Tách / gộp hoá đơn (SRS-POS-05, P4.5).
 * - Tách: chọn số lượng từng dòng chuyển sang một hoá đơn mới (đơn chờ) → thanh toán riêng hai
 *   hoá đơn (1 → 2).
 * - Đơn chờ: lưu tạm đơn đang làm, mở lại, gộp nhiều đơn chờ vào đơn hiện tại (n → 1).
 */
export function SplitInvoiceModal({
  open,
  initialTab = "split",
  cart,
  held,
  online,
  onClose,
  onSplit,
  onHold,
  onResume,
  onMerge,
  onDiscard,
}: Props) {
  const [tab, setTab] = useState<Tab>(initialTab);
  const [pick, setPick] = useState<Record<string, number>>({});
  const [label, setLabel] = useState("");
  const [selected, setSelected] = useState<string[]>([]);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (!open) return;
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setTab(initialTab);
    setPick({});
    setLabel("");
    setSelected([]);
  }, [open, initialTab]);

  // Gift lines are generated by promotions — only real lines can move
  const lines = useMemo(() => (cart?.lines ?? []).filter((l) => !l.isGift), [cart]);
  const moving = lines.filter((l) => (pick[l.id] ?? 0) > 0);
  const movingValue = moving.reduce(
    (s, l) => s + (l.totalAmount / l.quantity) * (pick[l.id] ?? 0),
    0,
  );

  async function run(fn: () => Promise<void>, close = false) {
    setBusy(true);
    try {
      await fn();
      if (close) onClose();
    } catch {
      /* the hook already toasted the error */
    } finally {
      setBusy(false);
    }
  }

  function setQty(id: string, q: number, max: number) {
    setPick((p) => ({ ...p, [id]: Math.max(0, Math.min(max, q)) }));
  }

  return (
    <Modal open={open} onClose={onClose} title="Tách / gộp hoá đơn" size="lg">
      <div className="mb-4 flex rounded-lg bg-gray-100 p-1 text-sm" role="tablist">
        {(
          [
            ["split", "Tách hoá đơn"],
            ["held", `Đơn chờ (${held.length})`],
          ] as const
        ).map(([k, t]) => (
          <button
            key={k}
            role="tab"
            aria-selected={tab === k}
            onClick={() => setTab(k)}
            className={cn(
              "h-10 flex-1 rounded-md",
              tab === k ? "bg-white font-semibold shadow" : "text-gray-600",
            )}
          >
            {t}
          </button>
        ))}
      </div>

      {!online && (
        <p className="mb-3 rounded-lg bg-amber-50 p-3 text-sm text-amber-800">
          Đang ở chế độ cục bộ — tách / gộp / lưu tạm cần kết nối máy chủ POS.
        </p>
      )}

      {tab === "split" ? (
        lines.length === 0 ? (
          <p className="py-8 text-center text-gray-400">Giỏ hàng trống</p>
        ) : (
          <div className="flex flex-col gap-3">
            <p className="text-sm text-gray-600">
              Chọn số lượng chuyển sang <strong>hoá đơn mới</strong>. Phần còn lại thanh toán trước;
              hoá đơn mới nằm trong “Đơn chờ”.
            </p>
            <div className="max-h-[45vh] overflow-y-auto rounded-lg border border-gray-200">
              {lines.map((l) => {
                const q = pick[l.id] ?? 0;
                return (
                  <div
                    key={l.id}
                    className="flex items-center gap-3 border-b border-gray-100 px-3 py-2 last:border-0"
                  >
                    <div className="min-w-0 flex-1">
                      <p className="truncate font-medium">{l.name}</p>
                      <p className="text-xs text-gray-500">
                        Trong giỏ: {l.quantity} · {fmtMoney(l.unitPrice)}
                      </p>
                    </div>
                    <div className="flex items-center gap-1">
                      <button
                        aria-label={`Bớt ${l.name}`}
                        onClick={() => setQty(l.id, q - 1, l.quantity)}
                        className="flex h-11 w-11 items-center justify-center rounded-lg border border-gray-200"
                      >
                        <Minus className="h-4 w-4" />
                      </button>
                      <input
                        value={q}
                        onChange={(e) => setQty(l.id, Number(e.target.value) || 0, l.quantity)}
                        inputMode="decimal"
                        aria-label={`Số lượng tách ${l.name}`}
                        className="h-11 w-14 rounded-lg border border-gray-300 text-center text-base"
                      />
                      <button
                        aria-label={`Thêm ${l.name}`}
                        onClick={() => setQty(l.id, q + 1, l.quantity)}
                        className="flex h-11 w-11 items-center justify-center rounded-lg border border-gray-200"
                      >
                        <Plus className="h-4 w-4" />
                      </button>
                      <button
                        onClick={() => setQty(l.id, l.quantity, l.quantity)}
                        className="h-11 rounded-lg px-2 text-xs text-blue-600 hover:bg-blue-50"
                      >
                        Tất cả
                      </button>
                    </div>
                  </div>
                );
              })}
            </div>
            <input
              value={label}
              onChange={(e) => setLabel(e.target.value)}
              placeholder="Tên hoá đơn mới (vd. Bàn 2, Khách B) — tuỳ chọn"
              aria-label="Tên hoá đơn tách"
              className="h-11 rounded-lg border border-gray-300 px-3 text-sm"
            />
            <div className="flex items-center justify-between">
              <p className="text-sm text-gray-600">
                Chuyển {moving.length} dòng · ~{fmtMoney(movingValue)}
              </p>
              <button
                disabled={busy || !online || moving.length === 0}
                onClick={() =>
                  run(
                    () =>
                      onSplit(
                        moving.map((l) => ({ itemId: l.id, quantity: pick[l.id] })),
                        label || undefined,
                      ),
                    true,
                  )
                }
                className="flex h-12 items-center gap-2 rounded-xl bg-blue-600 px-5 font-semibold text-white disabled:opacity-40"
              >
                <Scissors className="h-5 w-5" /> Tách hoá đơn
              </button>
            </div>
          </div>
        )
      ) : (
        <div className="flex flex-col gap-3">
          <div className="flex flex-wrap gap-2">
            <button
              disabled={busy || !online || !cart?.lines.length}
              onClick={() => run(() => onHold(label || undefined))}
              className="flex h-11 items-center gap-2 rounded-lg border border-gray-300 px-4 text-sm disabled:opacity-40"
            >
              <PauseCircle className="h-4 w-4" /> Lưu tạm đơn hiện tại
            </button>
            <button
              disabled={busy || !online || selected.length === 0}
              onClick={() => run(() => onMerge(selected), true)}
              className="flex h-11 items-center gap-2 rounded-lg bg-blue-600 px-4 text-sm font-semibold text-white disabled:opacity-40"
            >
              <Combine className="h-4 w-4" /> Gộp {selected.length || ""} đơn vào đơn hiện tại
            </button>
          </div>
          {held.length === 0 ? (
            <p className="py-8 text-center text-gray-400">Chưa có đơn chờ</p>
          ) : (
            <div className="rounded-lg border border-gray-200">
              {held.map((h) => (
                <div
                  key={h.id}
                  className="flex items-center gap-3 border-b border-gray-100 px-3 py-2 last:border-0"
                >
                  <input
                    type="checkbox"
                    aria-label={`Chọn ${h.label}`}
                    checked={selected.includes(h.id)}
                    onChange={(e) =>
                      setSelected((s) =>
                        e.target.checked ? [...s, h.id] : s.filter((x) => x !== h.id),
                      )
                    }
                    className="h-5 w-5"
                  />
                  <div className="min-w-0 flex-1">
                    <p className="font-medium">{h.label}</p>
                    <p className="text-xs text-gray-500">
                      {h.itemCount} dòng · SL {h.quantity} · {fmtDate(h.createdAt, true)}
                    </p>
                  </div>
                  <button
                    disabled={busy || !online}
                    onClick={() => run(() => onResume(h.id), true)}
                    className="flex h-11 items-center gap-1 rounded-lg border border-gray-300 px-3 text-sm disabled:opacity-40"
                    title="Mở lại (đơn đang làm sẽ được lưu tạm)"
                  >
                    <Play className="h-4 w-4" /> Mở
                  </button>
                  <button
                    disabled={busy || !online}
                    aria-label={`Xoá ${h.label}`}
                    onClick={() =>
                      confirm(`Xoá đơn chờ "${h.label}"?`) && run(() => onDiscard(h.id))
                    }
                    className="flex h-11 w-11 items-center justify-center rounded-lg text-gray-400 hover:bg-red-50 hover:text-red-500 disabled:opacity-40"
                  >
                    <Trash2 className="h-4 w-4" />
                  </button>
                </div>
              ))}
            </div>
          )}
        </div>
      )}
    </Modal>
  );
}
