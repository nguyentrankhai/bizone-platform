#!/usr/bin/env node
// Connector plugin tooling (P7.1) — for plugin publishers and Payment Hub operators.
//
//   node scripts/connector-plugin.mjs keygen <keyId> [--out <dir>]
//       New Ed25519 publisher key: writes <dir>/<keyId>.private.pem (keep it secret, mode 600) and
//       prints the CONNECTOR_TRUSTED_KEYS entry the Payment Hub operator adds to the env.
//   node scripts/connector-plugin.mjs pack <pluginDir> --key <private.pem> --key-id <keyId> [--out <file.zip>]
//       Signs every file of <pluginDir> (hidden files and SIGNATURE.json excluded) and writes the zip.
//   node scripts/connector-plugin.mjs verify <file.zip>
//       Lists the package and checks its signature against CONNECTOR_TRUSTED_KEYS (env).
//   node scripts/connector-plugin.mjs embed-host
//       (Payment Hub developers) regenerate services/connectors/sandbox-host-source.ts from
//       services/connectors/sandbox-host.mjs after editing the sandbox host.
//
// The signed message must match services/connectors/package.ts (signedMessage) — tested in
// tests/connector-plugin.test.ts.

import {
  createHash,
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign,
  verify,
} from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { unzipSync, zipSync } from "fflate";

const SIGNATURE_FILE = "SIGNATURE.json";
const PREFIX = "payhub-connector-v1\n";

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

export function signedMessage(files) {
  const lines = [...files.keys()]
    .filter((p) => p !== SIGNATURE_FILE)
    .sort()
    .map((p) => `${p}\n${sha256(files.get(p))}\n`);
  return Buffer.from(PREFIX + lines.join(""), "utf8");
}

function walk(dir, base = dir, out = new Map()) {
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith(".")) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, base, out);
    else {
      const rel = path.relative(base, full).split(path.sep).join("/");
      if (rel !== SIGNATURE_FILE) out.set(rel, new Uint8Array(readFileSync(full)));
    }
  }
  return out;
}

/** Build a signed package (zip bytes) from a directory — exported for tests. */
export function pack(dir, privateKeyPem, keyId) {
  const files = walk(dir);
  if (!files.has("manifest.json")) throw new Error(`${dir}: manifest.json missing`);
  const signature = sign(null, signedMessage(files), createPrivateKey(privateKeyPem)).toString(
    "base64",
  );
  files.set(
    SIGNATURE_FILE,
    new TextEncoder().encode(JSON.stringify({ algorithm: "ed25519", keyId, signature }, null, 2)),
  );
  // fixed mtime → reproducible zip for the same content
  return zipSync(Object.fromEntries(files), { level: 9, mtime: new Date("2026-01-01T00:00:00Z") });
}

/** TS module embedding the sandbox host source (written to disk at runtime by sandbox.ts). */
export function embedHost(src) {
  return [
    "// GENERATED by `node scripts/connector-plugin.mjs embed-host` from ./sandbox-host.mjs — do not edit.",
    "// The host is written next to the extracted plugins at runtime, so it works whatever the working",
    "// directory / bundling of the process (next start, standalone, dist/worker.mjs). Test: same text.",
    `export const SANDBOX_HOST_SOURCE = ${JSON.stringify(src)};`,
    "",
  ].join("\n");
}

function arg(args, name) {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

function main(argv) {
  const [cmd, ...rest] = argv;
  if (cmd === "keygen") {
    const keyId = rest[0];
    if (!keyId || !/^[A-Za-z0-9_.-]{1,64}$/.test(keyId))
      throw new Error("keygen <keyId> (A-Z a-z 0-9 _ . -)");
    const outDir = arg(rest, "--out") ?? ".";
    const { privateKey, publicKey } = generateKeyPairSync("ed25519");
    mkdirSync(outDir, { recursive: true });
    const file = path.join(outDir, `${keyId}.private.pem`);
    writeFileSync(file, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
    const spki = publicKey.export({ type: "spki", format: "der" }).toString("base64");
    console.log(`Private key: ${file} (keep secret)`);
    console.log(`CONNECTOR_TRUSTED_KEYS entry:\n${keyId}=${spki}`);
    return;
  }
  if (cmd === "pack") {
    const dir = rest[0];
    const keyFile = arg(rest, "--key");
    const keyId = arg(rest, "--key-id");
    if (!dir || !keyFile || !keyId)
      throw new Error("pack <pluginDir> --key <private.pem> --key-id <keyId> [--out file.zip]");
    const manifest = JSON.parse(readFileSync(path.join(dir, "manifest.json"), "utf8"));
    const out = arg(rest, "--out") ?? `${manifest.code}-${manifest.version}.zip`;
    const zip = pack(dir, readFileSync(keyFile, "utf8"), keyId);
    writeFileSync(out, zip);
    console.log(
      `${out}: ${manifest.code} ${manifest.version}, ${zip.byteLength} bytes, signed by "${keyId}"`,
    );
    return;
  }
  if (cmd === "verify") {
    const file = rest[0];
    if (!file) throw new Error("verify <file.zip>");
    const files = new Map(Object.entries(unzipSync(new Uint8Array(readFileSync(file)))));
    for (const [p, d] of files) console.log(`${p.padEnd(40)} ${d.byteLength}`);
    const sig = JSON.parse(new TextDecoder().decode(files.get(SIGNATURE_FILE)));
    const keys = Object.fromEntries(
      (process.env.CONNECTOR_TRUSTED_KEYS ?? "")
        .split(",")
        .filter(Boolean)
        .map((e) => [e.slice(0, e.indexOf("=")).trim(), e.slice(e.indexOf("=") + 1).trim()]),
    );
    if (!keys[sig.keyId]) {
      console.log(`Signed by "${sig.keyId}" — not in CONNECTOR_TRUSTED_KEYS`);
      process.exitCode = 1;
      return;
    }
    const key = createPublicKey({
      key: Buffer.from(keys[sig.keyId], "base64"),
      format: "der",
      type: "spki",
    });
    const ok = verify(null, signedMessage(files), key, Buffer.from(sig.signature, "base64"));
    console.log(ok ? `Signature OK ("${sig.keyId}")` : "Signature INVALID");
    if (!ok) process.exitCode = 1;
    return;
  }
  if (cmd === "embed-host") {
    const here = path.dirname(new URL(import.meta.url).pathname);
    const src = readFileSync(path.join(here, "../services/connectors/sandbox-host.mjs"), "utf8");
    writeFileSync(path.join(here, "../services/connectors/sandbox-host-source.ts"), embedHost(src));
    console.log("services/connectors/sandbox-host-source.ts regenerated");
    return;
  }
  throw new Error("usage: keygen | pack | verify | embed-host (see the header of this file)");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  }
}
