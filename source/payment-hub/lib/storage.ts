import { createHash, createHmac } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * File storage for dispute evidence (P5.6). Driver by env:
 *  - S3 / MinIO when `S3_ENDPOINT` is set (or STORAGE_DRIVER=s3): path-style requests signed with
 *    AWS Signature V4 (no SDK — only PUT / GET / DELETE of one object + bucket bootstrap). The bucket
 *    (`S3_BUCKET`, default `payment-hub`) is created on first use.
 *  - local directory otherwise (`STORAGE_LOCAL_DIR`, default `./storage`) — dev / single instance.
 * Keys are generated by the server (never from user input).
 */

export interface StoredObject {
  body: Buffer;
  contentType: string | null;
}

export interface StorageDriver {
  readonly name: "s3" | "local";
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredObject | null>;
  delete(key: string): Promise<void>;
}

export class StorageError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "StorageError";
  }
}

const KEY_RE = /^[A-Za-z0-9][A-Za-z0-9._/-]{0,400}$/;
function assertKey(key: string): void {
  if (!KEY_RE.test(key) || key.includes("..")) throw new StorageError(`Invalid storage key`);
}

// ─── S3 / MinIO (Signature V4) ────────────────────────────────────────────────

export interface S3Config {
  endpoint: string;
  region: string;
  bucket: string;
  accessKey: string;
  secretKey: string;
}

const sha256Hex = (data: Buffer | string) => createHash("sha256").update(data).digest("hex");
const hmac = (key: Buffer | string, data: string) =>
  createHmac("sha256", key).update(data).digest();

/** RFC 3986 encoding of each path segment (S3 canonical URI). */
function encodePath(p: string): string {
  return p
    .split("/")
    .map((seg) =>
      encodeURIComponent(seg).replace(
        /[!'()*]/g,
        (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`,
      ),
    )
    .join("/");
}

/** Authorization headers of a path-style S3 request (exported for tests). */
export function signS3Request(
  cfg: Pick<S3Config, "region" | "accessKey" | "secretKey">,
  req: { method: string; host: string; path: string; body: Buffer; now: Date },
): Record<string, string> {
  const amzDate = req.now
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\.\d{3}/, "");
  const date = amzDate.slice(0, 8);
  const payloadHash = sha256Hex(req.body);
  const headers: Record<string, string> = {
    host: req.host,
    "x-amz-content-sha256": payloadHash,
    "x-amz-date": amzDate,
  };
  const signedHeaders = Object.keys(headers).sort().join(";");
  const canonicalHeaders = Object.keys(headers)
    .sort()
    .map((h) => `${h}:${headers[h]}\n`)
    .join("");
  const canonicalRequest = [
    req.method,
    encodePath(req.path),
    "",
    canonicalHeaders,
    signedHeaders,
    payloadHash,
  ].join("\n");
  const scope = `${date}/${cfg.region}/s3/aws4_request`;
  const stringToSign = ["AWS4-HMAC-SHA256", amzDate, scope, sha256Hex(canonicalRequest)].join("\n");
  const kDate = hmac(`AWS4${cfg.secretKey}`, date);
  const kSigning = hmac(hmac(hmac(kDate, cfg.region), "s3"), "aws4_request");
  const signature = createHmac("sha256", kSigning).update(stringToSign).digest("hex");
  return {
    "x-amz-content-sha256": payloadHash,
    "x-amz-date": amzDate,
    authorization: `AWS4-HMAC-SHA256 Credential=${cfg.accessKey}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`,
  };
}

class S3Storage implements StorageDriver {
  readonly name = "s3" as const;
  private bucketReady: Promise<void> | null = null;
  constructor(private readonly cfg: S3Config) {}

  private async request(
    method: string,
    objectPath: string,
    body: Buffer = Buffer.alloc(0),
    extraHeaders: Record<string, string> = {},
  ): Promise<Response> {
    const base = new URL(this.cfg.endpoint);
    const path = `/${this.cfg.bucket}${objectPath ? `/${objectPath}` : ""}`;
    const auth = signS3Request(this.cfg, {
      method,
      host: base.host,
      path,
      body,
      now: new Date(),
    });
    const url = `${base.protocol}//${base.host}${encodePath(path)}`;
    try {
      return await fetch(url, {
        method,
        headers: { ...auth, ...extraHeaders },
        body: method === "PUT" ? new Uint8Array(body) : undefined,
        signal: AbortSignal.timeout(20_000),
      });
    } catch (e) {
      throw new StorageError(`Storage unreachable: ${(e as Error).message}`);
    }
  }

  private ensureBucket(): Promise<void> {
    this.bucketReady ??= (async () => {
      const head = await this.request("HEAD", "");
      if (head.ok) return;
      if (head.status !== 404) throw new StorageError(`Storage bucket check: HTTP ${head.status}`);
      const created = await this.request("PUT", "");
      // 409 BucketAlreadyOwnedByYou — created concurrently
      if (!created.ok && created.status !== 409) {
        throw new StorageError(`Cannot create bucket ${this.cfg.bucket}: HTTP ${created.status}`);
      }
    })().catch((e: unknown) => {
      this.bucketReady = null;
      throw e;
    });
    return this.bucketReady;
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    assertKey(key);
    await this.ensureBucket();
    const res = await this.request("PUT", key, body, { "content-type": contentType });
    if (!res.ok) {
      const text = await res.text().catch(() => "");
      throw new StorageError(`Upload failed: HTTP ${res.status} ${text.slice(0, 200)}`);
    }
  }

  async get(key: string): Promise<StoredObject | null> {
    assertKey(key);
    const res = await this.request("GET", key);
    if (res.status === 404) return null;
    if (!res.ok) throw new StorageError(`Download failed: HTTP ${res.status}`);
    return {
      body: Buffer.from(await res.arrayBuffer()),
      contentType: res.headers.get("content-type"),
    };
  }

  async delete(key: string): Promise<void> {
    assertKey(key);
    const res = await this.request("DELETE", key);
    if (!res.ok && res.status !== 404) throw new StorageError(`Delete failed: HTTP ${res.status}`);
  }
}

// ─── Local directory ──────────────────────────────────────────────────────────

class LocalStorage implements StorageDriver {
  readonly name = "local" as const;
  constructor(private readonly root: string) {}

  private fileOf(key: string): string {
    assertKey(key);
    const file = path.resolve(this.root, key);
    if (!file.startsWith(path.resolve(this.root) + path.sep)) {
      throw new StorageError("Invalid storage key");
    }
    return file;
  }

  async put(key: string, body: Buffer): Promise<void> {
    const file = this.fileOf(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
  }

  async get(key: string): Promise<StoredObject | null> {
    try {
      return { body: await readFile(this.fileOf(key)), contentType: null };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.fileOf(key), { force: true });
  }
}

// ─── Factory ──────────────────────────────────────────────────────────────────

function localDir(): string {
  return process.env.STORAGE_LOCAL_DIR || "storage";
}

const globalForStorage = globalThis as unknown as { payhubStorage?: StorageDriver };

export function getStorage(): StorageDriver {
  if (!globalForStorage.payhubStorage) {
    const driver = process.env.STORAGE_DRIVER ?? (process.env.S3_ENDPOINT ? "s3" : "local");
    if (driver === "s3") {
      const endpoint = process.env.S3_ENDPOINT;
      const accessKey = process.env.S3_ACCESS_KEY;
      const secretKey = process.env.S3_SECRET_KEY;
      if (!endpoint || !accessKey || !secretKey) {
        throw new StorageError("STORAGE_DRIVER=s3 needs S3_ENDPOINT, S3_ACCESS_KEY, S3_SECRET_KEY");
      }
      globalForStorage.payhubStorage = new S3Storage({
        endpoint,
        accessKey,
        secretKey,
        region: process.env.S3_REGION || "us-east-1",
        bucket: process.env.S3_BUCKET || "payment-hub",
      });
    } else {
      globalForStorage.payhubStorage = new LocalStorage(
        // runtime directory — not something to trace into the build output
        path.resolve(/* turbopackIgnore: true */ process.cwd(), localDir()),
      );
    }
  }
  return globalForStorage.payhubStorage;
}
